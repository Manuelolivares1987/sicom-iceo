DROP FUNCTION IF EXISTS rpc_proveedor_rapido(VARCHAR, VARCHAR, VARCHAR);
CREATE OR REPLACE FUNCTION rpc_proveedor_rapido(
    p_nombre VARCHAR, p_rut VARCHAR DEFAULT NULL, p_tipo VARCHAR DEFAULT 'otros',
    p_rubro TEXT DEFAULT NULL, p_giro TEXT DEFAULT NULL
) RETURNS JSONB LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE
    v_rol TEXT := fn_user_rol(); v_rut TEXT; v_id UUID; v_codigo VARCHAR; v_nombre TEXT; v_i INT := 0;
BEGIN
    IF auth.uid() IS NULL THEN RAISE EXCEPTION 'No autenticado'; END IF;
    IF v_rol NOT IN ('administrador','subgerente_operaciones','jefe_mantenimiento','supervisor',
                     'operador_abastecimiento','bodeguero') THEN
        RAISE EXCEPTION 'Sin permiso para crear proveedores (rol: %)', v_rol; END IF;
    v_nombre := NULLIF(regexp_replace(UPPER(TRIM(COALESCE(p_nombre,''))), '\s+', ' ', 'g'), '');
    IF v_nombre IS NULL OR length(v_nombre) < 3 THEN
        RAISE EXCEPTION 'El nombre del proveedor es obligatorio (mínimo 3 letras)'; END IF;
    IF p_tipo NOT IN ('combustible','repuestos','servicios','lubricantes','filtros','otros') THEN
        RAISE EXCEPTION 'Tipo de proveedor inválido: %', p_tipo; END IF;
    IF p_rubro IS NOT NULL AND NOT fn_rubro_valido(p_rubro) THEN
        RAISE EXCEPTION 'Rubro inválido: %', p_rubro; END IF;

    v_rut := fn_normalizar_rut(p_rut);
    IF v_rut IS NOT NULL THEN
        IF v_rut !~ '^[0-9]{7,8}[0-9K]$' THEN
            RAISE EXCEPTION 'RUT inválido: % (formato 12.345.678-9)', p_rut; END IF;
        SELECT id INTO v_id FROM proveedores WHERE fn_normalizar_rut(rut) = v_rut LIMIT 1;
        IF v_id IS NOT NULL THEN
            UPDATE proveedores SET activo = true, updated_at = NOW() WHERE id = v_id AND NOT activo;
            RETURN jsonb_build_object('success', true, 'proveedor_id', v_id, 'existia', true);
        END IF;
        v_codigo := left(v_rut, length(v_rut)-1);
        IF EXISTS (SELECT 1 FROM proveedores WHERE codigo = v_codigo) THEN
            v_codigo := v_codigo || '-' || right(v_rut,1);
        END IF;
    ELSE
        SELECT id INTO v_id FROM proveedores WHERE UPPER(nombre) = v_nombre LIMIT 1;
        IF v_id IS NOT NULL THEN
            RETURN jsonb_build_object('success', true, 'proveedor_id', v_id, 'existia', true);
        END IF;
        LOOP
            v_codigo := 'PRV-' || UPPER(LEFT(md5(gen_random_uuid()::text), 6));
            EXIT WHEN NOT EXISTS (SELECT 1 FROM proveedores WHERE codigo = v_codigo);
            v_i := v_i + 1;
            IF v_i > 5 THEN RAISE EXCEPTION 'No se pudo generar código único'; END IF;
        END LOOP;
    END IF;

    INSERT INTO proveedores (codigo, nombre, rut, tipo, activo, observaciones, rubro, giro,
                             es_persona_natural, rubro_fuente, rubro_confianza)
    VALUES (v_codigo, v_nombre, fn_formatear_rut(v_rut), p_tipo::tipo_proveedor_enum, true,
            'Creado desde ingreso de bodega', COALESCE(p_rubro, 'Otro'), NULLIF(TRIM(COALESCE(p_giro,'')),''),
            (p_rubro = 'Persona natural (honorarios / servicios)'), 'manual', 'alta')
    RETURNING id INTO v_id;
    RETURN jsonb_build_object('success', true, 'proveedor_id', v_id, 'existia', false, 'codigo', v_codigo);
END $$;
GRANT EXECUTE ON FUNCTION rpc_proveedor_rapido(VARCHAR, VARCHAR, VARCHAR, TEXT, TEXT) TO authenticated;

CREATE OR REPLACE FUNCTION rpc_proveedor_actualizar(
    p_id UUID, p_nombre VARCHAR DEFAULT NULL, p_rut VARCHAR DEFAULT NULL, p_tipo VARCHAR DEFAULT NULL,
    p_rubro TEXT DEFAULT NULL, p_giro TEXT DEFAULT NULL, p_contacto VARCHAR DEFAULT NULL,
    p_telefono VARCHAR DEFAULT NULL, p_email VARCHAR DEFAULT NULL, p_activo BOOLEAN DEFAULT NULL
) RETURNS JSONB LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE v_rol TEXT := fn_user_rol(); v_rut TEXT;
BEGIN
    IF auth.uid() IS NULL THEN RAISE EXCEPTION 'No autenticado'; END IF;
    IF v_rol NOT IN ('administrador','subgerente_operaciones','jefe_mantenimiento','supervisor',
                     'operador_abastecimiento','bodeguero') THEN
        RAISE EXCEPTION 'Sin permiso para editar proveedores (rol: %)', v_rol; END IF;
    IF NOT EXISTS (SELECT 1 FROM proveedores WHERE id = p_id) THEN RAISE EXCEPTION 'Proveedor no existe'; END IF;
    IF p_tipo IS NOT NULL AND p_tipo NOT IN ('combustible','repuestos','servicios','lubricantes','filtros','otros') THEN
        RAISE EXCEPTION 'Tipo inválido: %', p_tipo; END IF;
    IF p_rubro IS NOT NULL AND NOT fn_rubro_valido(p_rubro) THEN RAISE EXCEPTION 'Rubro inválido: %', p_rubro; END IF;
    IF p_rut IS NOT NULL THEN
        v_rut := fn_normalizar_rut(p_rut);
        IF v_rut IS NOT NULL AND v_rut !~ '^[0-9]{7,8}[0-9K]$' THEN RAISE EXCEPTION 'RUT inválido: %', p_rut; END IF;
        IF v_rut IS NOT NULL AND EXISTS (SELECT 1 FROM proveedores WHERE id <> p_id AND fn_normalizar_rut(rut) = v_rut) THEN
            RAISE EXCEPTION 'Ese RUT ya pertenece a otro proveedor'; END IF;
    END IF;

    UPDATE proveedores
       SET nombre   = COALESCE(NULLIF(regexp_replace(UPPER(TRIM(p_nombre)), '\s+', ' ', 'g'), ''), nombre),
           rut      = CASE WHEN p_rut IS NULL THEN rut ELSE fn_formatear_rut(v_rut) END,
           tipo     = COALESCE(p_tipo::tipo_proveedor_enum, tipo),
           rubro    = COALESCE(p_rubro, rubro),
           giro     = CASE WHEN p_giro IS NULL THEN giro ELSE NULLIF(TRIM(p_giro), '') END,
           contacto = COALESCE(p_contacto, contacto),
           telefono = COALESCE(p_telefono, telefono),
           email    = COALESCE(p_email, email),
           activo   = COALESCE(p_activo, activo),
           es_persona_natural = CASE WHEN p_rubro IS NULL THEN es_persona_natural
                                     ELSE p_rubro = 'Persona natural (honorarios / servicios)' END,
           rubro_fuente = CASE WHEN p_rubro IS NOT NULL OR p_giro IS NOT NULL THEN 'manual' ELSE rubro_fuente END,
           rubro_confianza = CASE WHEN p_rubro IS NOT NULL OR p_giro IS NOT NULL THEN 'alta' ELSE rubro_confianza END,
           updated_at = NOW()
     WHERE id = p_id;
    RETURN jsonb_build_object('success', true, 'proveedor_id', p_id);
END $$;
GRANT EXECUTE ON FUNCTION rpc_proveedor_actualizar(UUID, VARCHAR, VARCHAR, VARCHAR, TEXT, TEXT, VARCHAR, VARCHAR, VARCHAR, BOOLEAN) TO authenticated;

