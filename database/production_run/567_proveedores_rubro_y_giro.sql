   SET nombre = regexp_replace(UPPER(TRIM(nombre)), '\s+', ' ', 'g'), updated_at = NOW()
 WHERE observaciones LIKE 'Maestro auxiliares Softland%'
   AND nombre <> regexp_replace(UPPER(TRIM(nombre)), '\s+', ' ', 'g');

-- Códigos de 9 dígitos: CodAux traía el DV pegado. RUT real = 8 primeros dígitos.
DO $$
DECLARE r RECORD; v_num TEXT; v_dv TEXT; v_s INT; v_m INT; v_c TEXT; v_i INT; v_rutn TEXT;
BEGIN
    FOR r IN SELECT id, codigo, nombre FROM proveedores WHERE codigo ~ '^[0-9]{9}$' LOOP
        v_num := left(r.codigo, 8);
        -- DV módulo 11
        v_s := 0; v_m := 2;
        FOR v_i IN REVERSE 8..1 LOOP
            v_s := v_s + substr(v_num, v_i, 1)::INT * v_m;
            v_m := CASE WHEN v_m = 7 THEN 2 ELSE v_m + 1 END;
        END LOOP;
        v_i := 11 - (v_s % 11);
        v_dv := CASE WHEN v_i = 11 THEN '0' WHEN v_i = 10 THEN 'K' ELSE v_i::TEXT END;
        v_rutn := v_num || v_dv;

        IF EXISTS (SELECT 1 FROM proveedores p WHERE p.id <> r.id AND (p.codigo = v_num OR fn_normalizar_rut(p.rut) = v_rutn)) THEN
            -- Ya existe el mismo RUT: el repetido se desactiva y queda anotado
            UPDATE proveedores SET activo = false,
                   observaciones = COALESCE(observaciones,'') || ' · DUPLICADO de ' || v_num || ' (código Softland con DV pegado)',
                   updated_at = NOW()
             WHERE id = r.id;
            RAISE NOTICE 'duplicado desactivado: % (%)', r.nombre, r.codigo;
        ELSE
            UPDATE proveedores SET codigo = v_num, rut = fn_formatear_rut(v_rutn),
                   observaciones = COALESCE(observaciones,'') || ' · RUT corregido (Softland traía el DV en el código)',
                   updated_at = NOW()
             WHERE id = r.id;
            RAISE NOTICE 'RUT corregido: % → %', r.codigo, fn_formatear_rut(v_rutn);
        END IF;
    END LOOP;
END $$;

