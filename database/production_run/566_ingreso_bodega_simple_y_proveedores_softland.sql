-- ── 2. Proveedor rápido ──────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION fn_normalizar_rut(p_rut TEXT)
RETURNS TEXT LANGUAGE sql IMMUTABLE AS $$
    -- '77.268.280-8' / '77268280-8' / '772682808' → '772682808' (sin puntos ni guion, K mayúscula)
    SELECT NULLIF(UPPER(regexp_replace(COALESCE(p_rut,''), '[^0-9kK]', '', 'g')), '');
$$;

CREATE OR REPLACE FUNCTION fn_formatear_rut(p_rut_norm TEXT)
RETURNS TEXT LANGUAGE plpgsql IMMUTABLE AS $$
DECLARE v_num TEXT; v_dv TEXT; v_out TEXT := ''; v_i INT := 0;
BEGIN
    IF p_rut_norm IS NULL OR length(p_rut_norm) < 2 THEN RETURN p_rut_norm; END IF;
    v_num := left(p_rut_norm, length(p_rut_norm)-1);
    v_dv  := right(p_rut_norm, 1);
    FOR i IN REVERSE length(v_num)..1 LOOP
        v_out := substr(v_num, i, 1) || v_out;
        v_i := v_i + 1;
        IF v_i % 3 = 0 AND i > 1 THEN v_out := '.' || v_out; END IF;
    END LOOP;
    RETURN v_out || '-' || v_dv;
END $$;

CREATE OR REPLACE FUNCTION rpc_proveedor_rapido(
    p_nombre VARCHAR, p_rut VARCHAR DEFAULT NULL, p_tipo VARCHAR DEFAULT 'otros'
) RETURNS JSONB LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE
    v_rol TEXT := fn_user_rol(); v_rut TEXT; v_id UUID; v_codigo VARCHAR; v_nombre TEXT; v_i INT := 0;
BEGIN
    IF auth.uid() IS NULL THEN RAISE EXCEPTION 'No autenticado'; END IF;
    IF v_rol NOT IN ('administrador','subgerente_operaciones','jefe_mantenimiento','supervisor',
                     'operador_abastecimiento','bodeguero') THEN
        RAISE EXCEPTION 'Sin permiso para crear proveedores (rol: %)', v_rol; END IF;
    v_nombre := NULLIF(regexp_replace(TRIM(COALESCE(p_nombre,'')), '\s+', ' ', 'g'), '');
    IF v_nombre IS NULL OR length(v_nombre) < 3 THEN
        RAISE EXCEPTION 'El nombre del proveedor es obligatorio (mínimo 3 letras)'; END IF;
    IF p_tipo NOT IN ('combustible','repuestos','servicios','lubricantes','filtros','otros') THEN
        RAISE EXCEPTION 'Tipo de proveedor inválido: %', p_tipo; END IF;

    v_rut := fn_normalizar_rut(p_rut);
    IF v_rut IS NOT NULL THEN
        IF v_rut !~ '^[0-9]{7,8}[0-9K]$' THEN
            RAISE EXCEPTION 'RUT inválido: % (formato 12.345.678-9)', p_rut; END IF;
        -- Ya existe por RUT → devolver el que hay (idempotente)
        SELECT id INTO v_id FROM proveedores WHERE fn_normalizar_rut(rut) = v_rut LIMIT 1;
        IF v_id IS NOT NULL THEN
            UPDATE proveedores SET activo = true, updated_at = NOW() WHERE id = v_id AND NOT activo;
            RETURN jsonb_build_object('success', true, 'proveedor_id', v_id, 'existia', true);
        END IF;
        v_codigo := left(v_rut, length(v_rut)-1);
        IF EXISTS (SELECT 1 FROM proveedores WHERE codigo = v_codigo) THEN
            v_codigo := v_codigo || '-' || right(v_rut,1);
        END IF;
    ELSE
        -- Sin RUT: mismo nombre ya existente → devolverlo
        SELECT id INTO v_id FROM proveedores WHERE UPPER(nombre) = UPPER(v_nombre) LIMIT 1;
        IF v_id IS NOT NULL THEN
            RETURN jsonb_build_object('success', true, 'proveedor_id', v_id, 'existia', true);
        END IF;
        LOOP
            v_codigo := 'PRV-' || UPPER(LEFT(md5(gen_random_uuid()::text), 6));
            EXIT WHEN NOT EXISTS (SELECT 1 FROM proveedores WHERE codigo = v_codigo);
            v_i := v_i + 1;
            IF v_i > 5 THEN RAISE EXCEPTION 'No se pudo generar código único'; END IF;
        END LOOP;
    END IF;

    INSERT INTO proveedores (codigo, nombre, rut, tipo, activo, observaciones)
    VALUES (v_codigo, v_nombre, fn_formatear_rut(v_rut), p_tipo::tipo_proveedor_enum, true,
            'Creado desde ingreso de bodega')
    RETURNING id INTO v_id;
    RETURN jsonb_build_object('success', true, 'proveedor_id', v_id, 'existia', false, 'codigo', v_codigo);
END $$;
GRANT EXECUTE ON FUNCTION rpc_proveedor_rapido(VARCHAR, VARCHAR, VARCHAR) TO authenticated;

-- ── 3. Producto rápido acepta las categorías del catálogo ────────────────────
CREATE OR REPLACE FUNCTION public.rpc_producto_rapido(
    p_nombre character varying, p_categoria character varying DEFAULT 'repuesto'::character varying,
    p_unidad character varying DEFAULT 'unidad'::character varying, p_codigo character varying DEFAULT NULL::character varying
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $function$
DECLARE
    v_rol TEXT := fn_user_rol(); v_codigo VARCHAR; v_id UUID; v_i INT := 0;
BEGIN
    IF auth.uid() IS NULL THEN RAISE EXCEPTION 'No autenticado'; END IF;
    IF v_rol NOT IN ('administrador','subgerente_operaciones','jefe_mantenimiento','supervisor',
                     'operador_abastecimiento','bodeguero') THEN
        RAISE EXCEPTION 'Sin permiso para crear productos (rol: %)', v_rol; END IF;
    IF NULLIF(TRIM(COALESCE(p_nombre,'')),'') IS NULL THEN
        RAISE EXCEPTION 'El nombre es obligatorio'; END IF;
    IF p_categoria NOT IN ('combustible','lubricante','filtro','repuesto','consumible','epp')
       AND NOT EXISTS (SELECT 1 FROM producto_categorias WHERE codigo = p_categoria AND activo) THEN
        RAISE EXCEPTION 'Categoría inválida: %', p_categoria; END IF;

    v_codigo := NULLIF(TRIM(COALESCE(p_codigo,'')),'');
    IF v_codigo IS NULL THEN
        LOOP
            v_codigo := 'REP-' || UPPER(LEFT(md5(gen_random_uuid()::text), 6));
            EXIT WHEN NOT EXISTS (SELECT 1 FROM productos WHERE codigo = v_codigo);
            v_i := v_i + 1;
            IF v_i > 5 THEN RAISE EXCEPTION 'No se pudo generar código único'; END IF;
        END LOOP;
    ELSIF EXISTS (SELECT 1 FROM productos WHERE codigo = v_codigo) THEN
        RAISE EXCEPTION 'El código % ya existe', v_codigo;
    END IF;

    INSERT INTO productos (codigo, nombre, categoria, unidad_medida)
    VALUES (v_codigo, TRIM(p_nombre), p_categoria, COALESCE(NULLIF(TRIM(COALESCE(p_unidad,'')),''),'unidad'))
    RETURNING id INTO v_id;
    RETURN jsonb_build_object('success', true, 'producto_id', v_id, 'codigo', v_codigo);
END $function$;

-- ── 4. Ingreso simple: proveedor + documento + ítems → stock ─────────────────
CREATE OR REPLACE FUNCTION rpc_ingreso_bodega_simple(
    p_proveedor_id UUID,
    p_bodega_id    UUID,
    p_doc_tipo     tipo_documento_proveedor_enum,
    p_doc_numero   VARCHAR,
    p_items        JSONB,               -- [{producto_id, cantidad, costo_unitario, lote?, vencimiento?, observacion?}]
    p_doc_fecha    DATE    DEFAULT NULL,
    p_evidencia_url TEXT   DEFAULT NULL,
    p_observacion  TEXT    DEFAULT NULL
) RETURNS JSONB LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE
    v_user   UUID := auth.uid();
    v_rol    TEXT := fn_user_rol();
    v_folio  VARCHAR; v_rec UUID; v_item JSONB; v_prod RECORD; v_bod RECORD; v_prov RECORD;
    v_cant NUMERIC; v_costo NUMERIC; v_provisional BOOLEAN; v_obs TEXT; v_unidad TEXT;
    v_rec_item UUID; v_capa UUID; v_n INT := 0; v_n_prov INT := 0;
    v_restante NUMERIC; v_oci RECORD; v_aplica NUMERIC; v_oc_items_tocados UUID[] := '{}';
    v_atendidas JSONB := '[]'::JSONB; v_r RECORD; v_dup RECORD; v_doc VARCHAR;
BEGIN
    IF v_user IS NULL THEN RAISE EXCEPTION 'No autenticado'; END IF;
    IF v_rol NOT IN ('administrador','subgerente_operaciones','jefe_mantenimiento','supervisor',
                     'operador_abastecimiento','bodeguero') THEN
        RAISE EXCEPTION 'Sin permiso para ingresar mercadería (rol: %)', v_rol; END IF;

    v_doc := NULLIF(TRIM(COALESCE(p_doc_numero,'')), '');
    IF v_doc IS NULL THEN RAISE EXCEPTION 'Falta el número de la factura o guía'; END IF;
    IF p_items IS NULL OR jsonb_typeof(p_items) <> 'array' OR jsonb_array_length(p_items) = 0 THEN
        RAISE EXCEPTION 'Agrega al menos un producto'; END IF;

    SELECT * INTO v_prov FROM proveedores WHERE id = p_proveedor_id;
    IF v_prov.id IS NULL THEN RAISE EXCEPTION 'Proveedor no existe'; END IF;
    SELECT * INTO v_bod FROM bodegas WHERE id = p_bodega_id;
    IF v_bod.id IS NULL THEN RAISE EXCEPTION 'Bodega no existe'; END IF;

    -- Candado: mismo documento del mismo proveedor
    SELECT folio_recepcion, created_at INTO v_dup FROM recepciones_bodega
     WHERE proveedor_id = p_proveedor_id AND documento_proveedor_tipo = p_doc_tipo
       AND UPPER(TRIM(documento_proveedor_numero)) = UPPER(v_doc) AND estado <> 'anulada'
     LIMIT 1;
    IF v_dup.folio_recepcion IS NOT NULL THEN
        RAISE EXCEPTION '% N° % de % ya fue ingresada el % (folio %). Revisa "Últimos ingresos".',
            initcap(p_doc_tipo::text), v_doc, v_prov.nombre,
            to_char(v_dup.created_at AT TIME ZONE 'America/Santiago', 'DD-MM-YYYY HH24:MI'), v_dup.folio_recepcion;
    END IF;

    v_folio := fn_generar_folio_recepcion_bodega();
    v_rec := gen_random_uuid();
    INSERT INTO recepciones_bodega (
        id, folio_recepcion, orden_compra_id, proveedor_id, bodega_id,
        documento_proveedor_tipo, documento_proveedor_numero, documento_proveedor_fecha,
        recibido_por, observacion, evidencia_url, created_by
    ) VALUES (
        v_rec, v_folio, NULL, p_proveedor_id, p_bodega_id,
        p_doc_tipo, v_doc, p_doc_fecha,
        v_user, NULLIF(TRIM(COALESCE(p_observacion,'')),''), p_evidencia_url, v_user
    );

    FOR v_item IN SELECT * FROM jsonb_array_elements(p_items) LOOP
        IF NULLIF(v_item->>'producto_id','') IS NULL THEN
            RAISE EXCEPTION 'Cada línea necesita un producto del catálogo'; END IF;
        SELECT * INTO v_prod FROM productos WHERE id = (v_item->>'producto_id')::UUID;
        IF v_prod.id IS NULL THEN RAISE EXCEPTION 'Producto % no existe', v_item->>'producto_id'; END IF;

        v_cant := COALESCE((v_item->>'cantidad')::NUMERIC, 0);
        IF v_cant <= 0 THEN RAISE EXCEPTION 'Cantidad de "%" debe ser mayor a 0', v_prod.nombre; END IF;
        v_unidad := COALESCE(NULLIF(v_item->>'unidad',''), v_prod.unidad_medida, 'unidad');

        -- Costo: el de la factura; si no viene (guía), el último conocido; si no hay, $1 provisional.
        v_costo := COALESCE((v_item->>'costo_unitario')::NUMERIC, 0);
        v_provisional := FALSE;
        IF v_costo <= 0 THEN
            v_costo := COALESCE(v_prod.costo_unitario_actual, 0);
            IF v_costo <= 0 THEN v_costo := 1; END IF;
            v_provisional := TRUE;
            v_n_prov := v_n_prov + 1;
        END IF;
        v_obs := NULLIF(TRIM(COALESCE(v_item->>'observacion','')),'');
        IF v_provisional THEN
            v_obs := COALESCE(v_obs || ' · ', '') || 'COSTO PROVISIONAL (documento sin precio): corregir en Costos FIFO con la factura';
        END IF;

        v_rec_item := gen_random_uuid();
        INSERT INTO recepciones_bodega_items (
            id, recepcion_id, orden_compra_item_id, producto_id, cantidad_recibida,
            unidad, costo_unitario_clp, lote, fecha_vencimiento, observacion, recepcion_documental
        ) VALUES (
            v_rec_item, v_rec, NULL, v_prod.id, v_cant,
            v_unidad, v_costo,
            NULLIF(v_item->>'lote',''), NULLIF(v_item->>'vencimiento','')::DATE, v_obs, FALSE
        );

        v_capa := gen_random_uuid();
        INSERT INTO inventario_capas (
            id, producto_id, bodega_id, recepcion_bodega_id, recepcion_bodega_item_id,
            orden_compra_id, orden_compra_item_id, proveedor_id,
            fecha_recepcion, folio_recepcion, numero_oc,
            cantidad_inicial, cantidad_disponible, unidad, costo_unitario,
            lote, vencimiento, estado, created_by
        ) VALUES (
            v_capa, v_prod.id, p_bodega_id, v_rec, v_rec_item,
            NULL, NULL, p_proveedor_id,
            COALESCE(p_doc_fecha, CURRENT_DATE), v_folio, NULL,
            v_cant, v_cant, v_unidad, v_costo,
            NULLIF(v_item->>'lote',''), NULLIF(v_item->>'vencimiento','')::DATE, 'disponible', v_user
        );

        -- Stock legacy + kardex (mismo camino que la recepción contra OC)
        PERFORM rpc_registrar_entrada_inventario(
            p_bodega_id => p_bodega_id, p_producto_id => v_prod.id, p_cantidad => v_cant,
            p_costo_unitario => v_costo,
            p_documento_referencia => v_folio || ' ' || p_doc_tipo::text || ' ' || v_doc,
            p_usuario_id => v_user,
            p_lote => NULLIF(v_item->>'lote',''), p_fecha_vencimiento => NULLIF(v_item->>'vencimiento','')::DATE
        );

        -- Pedidos del taller esperando este producto (ítems de OC pendientes, MIG201):
        -- se les aplica lo recibido, del más antiguo al más nuevo. El trigger
        -- trg_recurso_recibido hace el resto (recurso → 'recibido' + campanita).
        v_restante := v_cant;
        FOR v_oci IN
            SELECT oci.id, oci.cantidad_comprada, oci.cantidad_recibida
              FROM ordenes_compra_items oci
              JOIN ordenes_compra oc ON oc.id = oci.orden_compra_id
             WHERE oci.producto_id = v_prod.id AND oci.requiere_stock
               AND oci.estado <> 'completo' AND oc.estado IN ('abierta','parcial')
               AND oci.cantidad_comprada > oci.cantidad_recibida
             ORDER BY oc.created_at, oci.created_at
             FOR UPDATE OF oci
        LOOP
            EXIT WHEN v_restante <= 0;
            v_aplica := LEAST(v_restante, v_oci.cantidad_comprada - v_oci.cantidad_recibida);
            UPDATE ordenes_compra_items
               SET cantidad_recibida = cantidad_recibida + v_aplica,
                   estado = CASE WHEN cantidad_recibida + v_aplica >= cantidad_comprada
                                 THEN 'completo'::estado_oc_item_enum ELSE 'parcial'::estado_oc_item_enum END
             WHERE id = v_oci.id;
            v_oc_items_tocados := v_oc_items_tocados || v_oci.id;
            v_restante := v_restante - v_aplica;

            FOR v_r IN
                SELECT ot.folio AS ot_folio, COALESCE(rs.descripcion, v_prod.nombre) AS descripcion
                  FROM ot_recursos_solicitados rs LEFT JOIN ordenes_trabajo ot ON ot.id = rs.ot_id
                 WHERE rs.oc_item_id = v_oci.id
            LOOP
                v_atendidas := v_atendidas || jsonb_build_object(
                    'ot_folio', v_r.ot_folio, 'descripcion', v_r.descripcion, 'cantidad', v_aplica);
            END LOOP;
        END LOOP;

        v_n := v_n + 1;
    END LOOP;

    -- Estado global de las OC tocadas
    UPDATE ordenes_compra oc
       SET estado = CASE
             WHEN NOT EXISTS (SELECT 1 FROM ordenes_compra_items i WHERE i.orden_compra_id = oc.id AND i.estado <> 'completo')
                 THEN 'cerrada'::estado_oc_enum
             ELSE 'parcial'::estado_oc_enum END,
           updated_at = NOW()
     WHERE oc.id IN (SELECT DISTINCT orden_compra_id FROM ordenes_compra_items WHERE id = ANY(v_oc_items_tocados));

    RETURN jsonb_build_object(
        'success', true, 'folio', v_folio, 'recepcion_id', v_rec,
        'items', v_n, 'items_costo_provisional', v_n_prov,
        'solicitudes_atendidas', v_atendidas
    );
END $$;
GRANT EXECUTE ON FUNCTION rpc_ingreso_bodega_simple(UUID, UUID, tipo_documento_proveedor_enum, VARCHAR, JSONB, DATE, TEXT, TEXT) TO authenticated;

-- ── 5. Recepción contra OC: el bodeguero también puede ───────────────────────
-- Se parcha la función vigente (MIG38) por texto, sin reescribirla: sólo se
-- agrega 'bodeguero' a la lista de roles autorizados.
DO $$
DECLARE v_def TEXT; v_new TEXT;
BEGIN
    SELECT pg_get_functiondef(p.oid) INTO v_def
      FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
     WHERE n.nspname = 'public' AND p.proname = 'rpc_registrar_recepcion_bodega';
    IF v_def LIKE '%''operador_abastecimiento'',''bodeguero''%' THEN
        RAISE NOTICE 'rpc_registrar_recepcion_bodega ya autoriza bodeguero';
        RETURN;
    END IF;
    v_new := replace(v_def,
        '''jefe_mantenimiento'',''operador_abastecimiento'') THEN',
        '''jefe_mantenimiento'',''operador_abastecimiento'',''bodeguero'') THEN');
    IF v_new = v_def THEN
        RAISE EXCEPTION 'STOP — no se encontró la lista de roles esperada en rpc_registrar_recepcion_bodega';
    END IF;
    EXECUTE v_new;
    RAISE NOTICE 'rpc_registrar_recepcion_bodega: bodeguero autorizado';
END $$;

