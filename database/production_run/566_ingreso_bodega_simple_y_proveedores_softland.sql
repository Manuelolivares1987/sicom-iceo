-- ============================================================================
-- SICOM-ICEO | 566 — Ingreso de mercadería a bodega contra factura o guía
--                    + maestro de proveedores de Softland
-- ============================================================================
-- Pedido Manuel (2026-09-17): las órdenes de compra las emite un externo (en
-- Softland). Bodega recibe contra FACTURA o, en su defecto, contra GUÍA, y lo
-- que necesita es subir el stock fácil. Hoy el único camino era crear (o
-- importar desde PDF) la OC en SICOM y después "recepcionarla": dos
-- recepciones en toda la vida del sistema, y el rol `bodeguero` (3 personas
-- reales) ni siquiera estaba autorizado en la RPC.
--
--   1. rpc_ingreso_bodega_simple: proveedor + documento + ítems → stock.
--      Sin OC. Crea la capa FIFO y sincroniza el stock legacy (mismo camino
--      que MIG37, reutiliza rpc_registrar_entrada_inventario).
--      · Candado: el mismo documento del mismo proveedor no entra dos veces.
--      · Guía sin precio: toma el último costo conocido del producto; si no
--        hay, $1 provisional y lo marca (se corrige en Costos FIFO al llegar
--        la factura).
--      · Si el producto tiene pedidos del taller esperando compra (MIG201,
--        ítems de OC pendientes), la cantidad recibida se les aplica sola:
--        el trigger existente los pasa a 'recibido' y avisa al jefe.
--   2. rpc_proveedor_rapido: crear proveedor desde la misma pantalla (RUT +
--      nombre). Idempotente por RUT. proveedores no tiene política INSERT,
--      así que sin esto sólo el service_role podía crearlos.
--   3. rpc_producto_rapido acepta las categorías de producto_categorias
--      (ferretería, oficina, etc.), no sólo las seis fijas.
--   4. rpc_registrar_recepcion_bodega (flujo contra OC) autoriza `bodeguero`.
--   5. recepciones_bodega.documento_proveedor_fecha (fecha del documento).
--   6. Carga de 2.317 proveedores desde el maestro de auxiliares de Softland
--      (proveedores.xlsx, CodAux = RUT sin DV). Se calcula el DV; se omiten
--      las camionetas, "DE PRUEBA" y los RUT ficticios (<1.000.000). Los que
--      ya existen por RUT (ENEX, ESMAX, COPEC, VOLVO) no se duplican.
-- ADITIVA, IDEMPOTENTE.
-- ============================================================================

-- ── 0. PRECHECKS ─────────────────────────────────────────────────────────────
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_proc WHERE proname='rpc_registrar_recepcion_bodega') THEN
        RAISE EXCEPTION 'STOP — falta rpc_registrar_recepcion_bodega (MIG37/38).';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_proc WHERE proname='rpc_registrar_entrada_inventario') THEN
        RAISE EXCEPTION 'STOP — falta rpc_registrar_entrada_inventario (legacy).';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_proc WHERE proname='rpc_producto_rapido') THEN
        RAISE EXCEPTION 'STOP — falta rpc_producto_rapido (MIG201).';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_enum e JOIN pg_type t ON t.oid=e.enumtypid
                   WHERE t.typname='rol_usuario_enum' AND e.enumlabel='bodeguero') THEN
        RAISE EXCEPTION 'STOP — el rol bodeguero no existe en rol_usuario_enum.';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.tables WHERE table_name='producto_categorias') THEN
        RAISE EXCEPTION 'STOP — falta producto_categorias.';
    END IF;
END $$;

