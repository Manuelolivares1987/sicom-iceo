-- Comercial (13 UF × meses arrendados) frente a la mantención que proyecta SICOM, 2027.
CREATE FUNCTION rpc_ppto_comercial() RETURNS JSONB
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path TO 'public' AS $$
DECLARE
    v_uf NUMERIC := coalesce((SELECT valor FROM ppto_supuesto WHERE clave = 'uf_valor'), 41200);
    v_ufm NUMERIC := coalesce((SELECT valor FROM ppto_supuesto WHERE clave = 'uf_mant_mes'), 13);
    r JSONB;
BEGIN
    IF NOT fn_costos_operacion_puede_ver() THEN
        RAISE EXCEPTION 'Sin permiso para ver costos de operación.' USING ERRCODE = '42501';
    END IF;
    WITH pr AS (
        SELECT linea, patente, mes, monto FROM ppto_resultado WHERE version_id = 1 AND anio = 2027
    ), cm AS (
        SELECT patente, min(codigo) AS codigo, min(tipo) AS tipo, min(area) AS area, min(fuente) AS fuente,
               count(*) AS meses, sum(ingreso) AS ingreso, array_agg(mes ORDER BY mes) AS lista
          FROM ppto_comercial_mes WHERE anio = 2027 GROUP BY 1
    ), sc AS (
        SELECT patente,
               sum(monto) FILTER (WHERE linea = 'A1') AS a1, sum(monto) FILTER (WHERE linea = 'A2') AS a2,
               sum(monto) FILTER (WHERE linea = 'A3') AS a3, sum(monto) FILTER (WHERE linea = 'A4') AS a4
          FROM pr WHERE patente IS NOT NULL AND linea IN ('A1','A2','A3','A4') GROUP BY 1
    ), pat AS (
        SELECT patente FROM cm UNION SELECT patente FROM sc
    ), mm AS (
        SELECT m AS mes,
               (SELECT count(*) FROM ppto_comercial_mes c WHERE c.anio = 2027 AND c.mes = m) AS camiones,
               coalesce((SELECT sum(monto) FROM pr WHERE pr.linea LIKE 'A%' AND pr.mes = m), 0)
             + coalesce((SELECT sum(monto) FROM pr WHERE pr.linea LIKE 'A%' AND pr.mes IS NULL), 0) / 12.0 AS sicom
          FROM generate_series(1, 12) m
    )
    SELECT jsonb_build_object(
        'uf', v_uf, 'uf_mes', v_ufm, 'cuota', v_uf * v_ufm,
        'meses_total', (SELECT count(*) FROM ppto_comercial_mes WHERE anio = 2027),
        'lineas', (SELECT jsonb_agg(jsonb_build_object(
                'codigo', l.codigo, 'nombre', l.nombre, 'metodo', l.metodo,
                'grupo', CASE WHEN l.codigo LIKE 'A%' THEN 'mantencion' WHEN l.codigo = 'B1' THEN 'excluido' ELSE 'aparte' END,
                'monto', round(coalesce((SELECT sum(monto) FROM pr WHERE pr.linea = l.codigo), 0))
            ) ORDER BY l.orden) FROM ppto_linea l WHERE l.codigo IN ('A1','A2','A3','A4','A5','B1','B3','C2')),
        'meses', (SELECT jsonb_agg(jsonb_build_object('mes', mes, 'camiones', camiones,
                'comercial', camiones * v_uf * v_ufm, 'sicom', round(sicom)) ORDER BY mes) FROM mm),
        'camiones', (SELECT coalesce(jsonb_agg(jsonb_build_object(
                'patente', p.patente, 'codigo', cm.codigo, 'tipo', cm.tipo,
                'area', coalesce(cm.area, 'Sin arriendo en Comercial'), 'fuente', cm.fuente,
                'modelo', c.modelo, 'anio_fab', c.anio_fab,
                'meses', coalesce(cm.meses, 0), 'lista', coalesce(to_jsonb(cm.lista), '[]'::jsonb),
                'ingreso', coalesce(cm.ingreso, 0), 'comercial', coalesce(cm.meses, 0) * v_uf * v_ufm,
                'preventivo', round(coalesce(sc.a1, 0)), 'correctivo', round(coalesce(sc.a2, 0)),
                'neumaticos', round(coalesce(sc.a3, 0)), 'mayores', round(coalesce(sc.a4, 0))
            ) ORDER BY coalesce(cm.meses, 0) DESC, coalesce(sc.a1,0)+coalesce(sc.a2,0)+coalesce(sc.a3,0)+coalesce(sc.a4,0) DESC), '[]')
              FROM pat p LEFT JOIN cm ON cm.patente = p.patente LEFT JOIN sc ON sc.patente = p.patente
              LEFT JOIN ppto_camion c ON c.patente = p.patente)
    ) INTO r;
    RETURN r;
END $$;

